"""One-command demo: data report, codec report, structure report, and what we REFUSE to do.

    python -m capacity_dataset.demo

Everything is synthetic and seeded, so the demo needs no external data. It writes
reference/data/demo_report.md (Markdown) and prints the same content.
"""
from __future__ import annotations

import pathlib
import time

import torch
import torch.nn as nn

import capacity_lens as CL

from .codec import codec_report
from .report import dup_report, recommend, saturation_report

OUT = pathlib.Path.cwd() / "demo_report.md"
D, C = 8, 4


def make(seed=0, n=2000, c=C, dup=0.2, flips=0.08, long_tail=True):
    """A dataset with the defects real corpora have: duplicates, label errors, imbalance."""
    g = torch.Generator().manual_seed(seed)
    if long_tail:
        w = torch.tensor([0.55, 0.25, 0.12, 0.08])[:c]
        w = w / w.sum()
        y = torch.multinomial(w, n, replacement=True, generator=g)
    else:
        y = torch.randint(0, c, (n,), generator=g)
    mu = torch.zeros(c, D)
    for j in range(c):
        mu[j, j % D] = 1.2 if long_tail else 1.6
    x = mu[y] + 0.9 * torch.randn(n, D, generator=g)
    y_true = y.clone()
    flip = torch.rand(n, generator=g) < flips
    y = torch.where(flip, torch.randint(0, c, (n,), generator=g), y)
    if dup > 0:
        m = int(n * dup)
        pick = torch.randperm(n, generator=g)[:m]
        x = torch.cat([x, x[pick]])
        y = torch.cat([y, y[pick]])
        y_true = torch.cat([y_true, y_true[pick]])
        flip = torch.cat([flip, flip[pick]])   # keep the error mask aligned with the duplicated rows
    return x, y, y_true, flip


def mlp(d_in, d_out, h=128):
    return nn.Sequential(nn.Linear(d_in, h), nn.ReLU(), nn.Linear(h, d_out))


def train(*mods, x=None, y=None, seed=0, epochs=10, lr=3e-3, bs=128):
    """Train one or more modules jointly (encoder+decoder pairs need this)."""
    torch.manual_seed(seed)
    params = [p for m in mods for p in m.parameters() if p.requires_grad]
    if not params:
        return mods[0] if mods else None
    opt = torch.optim.Adam(params, lr=lr)
    lossf = nn.CrossEntropyLoss(reduction="none")
    for _ in range(epochs):
        perm = torch.randperm(len(x))
        for i in range(0, len(x), bs):
            j = perm[i:i + bs]
            opt.zero_grad()
            out = x[j]
            for m in mods:
                out = m(out)
                if isinstance(out, tuple):
                    out = out[0]
            lossf(out, y[j]).mean().backward()
            opt.step()
    return mods[0] if mods else None


def acc(m, x, y):
    with torch.no_grad():
        return float((m(x).argmax(1) == y).float().mean())


def main():
    t0 = time.time()
    lines = []
    def p(s=""):
        print(s)
        lines.append(s)

    p("# capacity_dataset demo report")
    p("")
    p("Generated by `python -m capacity_dataset.demo` on synthetic data with known defects "
      "(20% duplicates, 8% label flips, long-tail classes). Every number below is measured in this run.")
    p("")

    x, y, y_true, flip = make()
    xte, yte, _, _ = make(seed=999, n=800, dup=0.0, flips=0.0, long_tail=False)
    p(f"## 1. Data report   (n={len(x)}, d={x.shape[1]}, C={C})")
    dup = dup_report(x, y)
    p("")
    p(f"- exact duplicate rate: **{dup['dup_rate_12dp']*100:.1f}%**")
    p(f"- rows whose identical feature vector carries different labels: **{dup['collisions_12dp']}**")
    p(f"- H(y) = {dup['h_y']:.3f}   R_IB(eps=0.10) = {dup['rib']:.3f}   K_min = {dup['k_min']}")
    p("")
    p("How to read: duplicate rate is measured on the raw feature vector at 12 decimals; a label collision "
      "means two rows are indistinguishable to any model, so those labels cannot both be learned.")
    t1 = time.time()
    sat = saturation_report(x, y, seed=0, epochs=10)
    p("")
    p(f"- level (70/30 split, {sat['train_rows']} train / {sat['test_rows']} test): {sat['level']:.3f}")
    p(f"- parameter knee: **{sat['param_knee']}**   sample knee: **{sat['sample_knee']}**")
    tag, why = recommend(dup, sat)
    p(f"- **recommendation: {tag}** -- {why}")
    p(f"- (data report took {time.time()-t1:.1f}s)")
    p("")

    p("## 2. Codec report   (encoder 8->3, decoder 3->4)")
    enc = nn.Sequential(nn.Linear(D, 64), nn.ReLU(), nn.Linear(64, 3))
    dec = nn.Linear(3, C)
    train(enc, dec, x=x, y=y, seed=0, epochs=8)   # train the PAIR: enc alone outputs 3 logits for 4 classes
    ref_model = mlp(D, C)
    train(ref_model, x=x, y=y, seed=1, epochs=10)
    ref_acc = acc(ref_model, xte, yte)
    rep = codec_report(enc, dec, x, y, reference_acc=ref_acc, epochs=10)
    p("")
    p(f"- reference accuracy (raw-input MLP): **{ref_acc:.3f}**")
    p(f"- H(Z) = {rep['h_z']:.3f} (capacity upper bound; reliable only for latent <= 6: "
      f"{rep['h_z_reliable']})")
    p(f"- I_lb(Z;Y) = {rep['i_lb']:.3f} (probe lower bound)")
    p(f"- current decoder {rep['acc_actual']:.3f} vs strong decoder {rep['acc_strong']:.3f} "
      f"(gap {rep['gap']:+.3f})")
    p(f"- **verdict: {rep['verdict']}**")
    p("")
    p("How to read: the verdict compares a strong decoder against the empirical reference. It says "
      "where the loss is, not how to fix it.")
    p("")

    p("## 3. Structure report   (budget ladder on the trained model)")
    lad = CL.budget_ladder(ref_model, x, y, ladder=tuple(round(0.05 * i, 2) for i in range(1, 13)),
                           n_random=3, seed=0)
    p("")
    p(f"- parameter knee: **{lad['knee_frac']}**  (smallest budget within 1% of the best)")
    p(f"- best score on the ladder: {lad['best_score']:.3f}")
    # rank allocation at exactly the knee budget
    shapes = [(m.weight.shape[1], m.weight.shape[0]) for m in ref_model if isinstance(m, nn.Linear)]
    caps = [min(sp) for sp in shapes]
    full = CL.rank_parameter_count(shapes, caps)
    budget = max(2 * CL.MIN_RANK * len(shapes), int(full * (lad["knee_frac"] or 0.5)))
    plan = CL.plan_rank_allocation(ref_model, x, y, budget)
    p(f"- allocation at {lad['knee_frac']}: uniform {plan['uniform_score']:.3f} -> planned "
      f"{plan['score']:.3f}  (ranks {plan['ranks']}, params {plan['params']} <= budget {budget})")
    p("  (if uniform and planned are equal the task is FLAT and allocation has nothing to win)")
    p("")

    p("## 4. What we refuse to do")
    p("")
    order = None
    with torch.no_grad():
        loss = nn.functional.cross_entropy(ref_model(x), y, reduction="none")
    order = torch.argsort(loss, descending=True)
    k10 = int(len(x) * 0.10)
    caught = float(flip[order[:k10]].sum())
    base = float(flip.float().mean())
    p(f"- A loss-ranked review list catches **{caught/max(float(flip.sum()),1e-9)*100:.0f}%** of the "
      f"injected label errors in the top 10% ({k10/max(caught,1e-9):.2f} rows per catch; random would be "
      f"{1/base:.2f}).")
    keep = order[int(len(x) * 0.05):]          # drop the worst 5% and retrain
    m2 = mlp(D, C)
    train(m2, x=x[keep], y=y[keep], seed=0, epochs=10)
    p(f"- Dropping those rows and retraining gives **{acc(m2, xte, yte):.3f}** vs "
      f"**{acc(ref_model, xte, yte):.3f}** without dropping -> the automatic cleanup does **not** pay.")
    p("- So we ship the review ranking and refuse to ship automatic cleaning. This demo measures that "
      "refusal instead of asserting it.")
    p("")
    p(f"_total demo time {time.time()-t0:.1f}s_")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\n[written] {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
